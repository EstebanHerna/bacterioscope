def _image_join_key(image_filename: str) -> str:
    stem = Path(image_filename).stem
    stem = stem.rstrip(".").strip()
    for suffix in (" original", ".original", "_original"):
        if stem.lower().endswith(suffix):
            stem = stem[: -len(suffix)].rstrip(". ").strip()
            break
    return stem


def _normalize_organism(organism: str) -> str:
    return " ".join(organism.strip().lower().replace("-komplex", " complex").split())


def _is_supported_enterobacterales(organism: str) -> bool:
    normalized = _normalize_organism(organism)
    return any(normalized.startswith(prefix) for prefix in _ENTEROBACTERALES_PREFIXES)


def derive_uzh_clsi_reference_rows(
    measurements: Iterable[Mapping[str, Any]],
    phenotype_records: Iterable[Mapping[str, Any]],
) -> list[dict[str, str]]:
    """Apply the Ed33 classifier to UZH numeric reference zones where eligible.

    Inclusion requires a mapped UZH drug code, an Enterobacterales organism,
    and matching EUCAST/CLSI disk content. Ineligible rows are retained with
    an explicit reason so the dataset denominator can be audited.
    """
    organism_by_image: dict[str, str] = {}
    ambiguous_images: set[str] = set()
    for record in phenotype_records:
        key = str(record.get("image_join_key", "")).strip().rstrip(".")
        organism = str(record.get("organism", "")).strip()
        if not key:
            continue
        if key in organism_by_image and organism_by_image[key] != organism:
            ambiguous_images.add(key)
        else:
            organism_by_image[key] = organism

    classifier = CLSIClassifier()
    derived: list[dict[str, str]] = []
    for source_row in measurements:
        image_filename = str(source_row.get("image_filename", "")).strip()
        image_key = _image_join_key(image_filename)
        code = str(source_row.get("antibiotic_code", "")).strip().upper()
        drug = UZH_CODE_TO_CLSI_DRUG.get(code, "")
        organism = organism_by_image.get(image_key, "")
        source_content = EUCAST_DISK_CONTENT_UG.get(code, "")
        clsi_content = CLSI_DISK_CONTENT_UG.get(drug, "") if drug else ""
        diameter_text = str(source_row.get("zone_diameter_mm_ref", "")).strip()
        category = ""
        status = "excluded"
        reason = ""

        if image_key in ambiguous_images:
            reason = "ambiguous_organism_for_image"
        elif not organism:
            reason = "organism_missing_from_uzh_source_labels"
        elif not _is_supported_enterobacterales(organism):
            reason = "organism_outside_classifier_group"
        elif not drug:
            reason = "antibiotic_code_not_in_classifier_scope"
        elif not source_content or not clsi_content:
            reason = "disk_content_not_documented_for_code"
        elif source_content != clsi_content:
            reason = "eucast_and_clsi_disk_contents_differ"
        else:
            try:
                diameter = float(diameter_text)
            except ValueError:
                reason = "invalid_reference_diameter"
            else:
                category = classifier.classify(drug, diameter).category
                if category == "UNKNOWN":
                    reason = "classifier_returned_unknown"
                    category = ""
                else:
                    status = "derived_analytical_label"

        derived.append(
            {
                "source": str(source_row.get("source", "")),
                "image_filename": image_filename,
                "image_join_key": image_key,
                "organism": organism,
                "antibiotic_code": code,
                "antibiotic_name_source": str(source_row.get("antibiotic_name", "")),
                "zone_diameter_mm_reference": diameter_text,
                "source_category_eucast": str(source_row.get("category_ref", "")),
                "source_standard": str(source_row.get("standard", "")),
                "source_standard_version_note": _EUCAST_VERSION_NOTE,
                "source_eucast_disk_content_ug": source_content,
                "clsi_ed33_disk_content_ug": clsi_content,
                "derived_category_clsi_ed33": category,
                "derivation_status": status,
                "exclusion_reason": reason,
                "breakpoint_table_version": BREAKPOINT_TABLE_VERSION,
                "label_basis": "BacterioScope CLSIClassifier applied to UZH/SIRscan reference zone",
                "independent_ground_truth": "false",
            }
        )
    return derived


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def write_derived_rows(path: Path, rows: Iterable[Mapping[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=OUTPUT_FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
